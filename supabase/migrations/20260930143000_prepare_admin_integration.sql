-- StreamFlix admin integration layer.
-- This migration is intentionally additive: existing application rows and
-- legacy columns are preserved while stable IDs, workflow fields, and missing
-- admin domains are introduced.

create or replace function public.is_master_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.admin
    where auth_user_id = (select auth.uid())
      and lower(replace(role, ' ', '')) = 'masteradmin'
  ) or exists (
    select 1
    from public."user"
    where auth_user_id = (select auth.uid())
      and lower(replace(user_role, ' ', '')) = 'masteradmin'
  );
$$;
create or replace function public.is_admin_role(required_role varchar)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select public.is_master_admin() or exists (
    select 1
    from public.admin
    where auth_user_id = (select auth.uid())
      and lower(replace(role, ' ', '')) = lower(replace(required_role, ' ', ''))
  );
$$;
create or replace function public.is_any_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select public.is_master_admin() or exists (
    select 1 from public.admin where auth_user_id = (select auth.uid())
  );
$$;
create or replace function public.get_admin_role()
returns varchar
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select case
    when public.is_master_admin() then 'masterAdmin'::varchar
    else (
      select role from public.admin
      where auth_user_id = (select auth.uid())
      limit 1
    )
  end;
$$;
